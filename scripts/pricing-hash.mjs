#!/usr/bin/env node
// The build's own pricing hash (spec C12, task WEB01). The API returns the SHA-256 of its copy of pricing.ts in `GET /v1/auth/me`; the website compares it
// with the SHA-256 of THIS repository's src/lib/pricing.ts, and on a difference the screen shows a banner and disables Save on bills.
//
//   node scripts/pricing-hash.mjs            writes src/lib/api/pricingHash.ts from the bytes of src/lib/pricing.ts (npm run pricing:hash; `npm run build` does it first)
//   node scripts/pricing-hash.mjs --check    changes nothing; exit 1 when the committed file is not what the script would write
//
// A static export cannot read a file at run time, and the single build-time variable of H4 is NEXT_PUBLIC_API_URL, so the hash lives in a generated source
// file. tests/unit/api-client.test.ts keeps it equal to the file (a stale copy fails `npm test`); the build writes it again, so a deployed site never carries a
// hash of a pricing.ts it was not built from.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const PRICING_FILE = 'src/lib/pricing.ts';
export const HASH_FILE = 'src/lib/api/pricingHash.ts';

/**
 * The SHA-256 (lower-case hex) of the bytes of the pricing file.
 * @param {string} [root]
 * @returns {string}
 */
export function pricingSha256(root = ROOT) {
  return createHash('sha256')
    .update(readFileSync(path.join(root, PRICING_FILE)))
    .digest('hex');
}

/**
 * The text of the generated file for a hash.
 * @param {string} sha256
 * @returns {string}
 */
export function renderHashFile(sha256) {
  return [
    '// GENERATED by scripts/pricing-hash.mjs from src/lib/pricing.ts (spec C12). Do not edit: `npm run pricing:hash` writes it, `npm run build` writes it first,',
    '// and tests/unit/api-client.test.ts fails when it is not the SHA-256 of the file.',
    '',
    '/** The SHA-256 of src/lib/pricing.ts as this build was made from it. `me` of the API must return the same. */',
    'export const BUILD_PRICING_SHA256 =',
    `  '${sha256}';`,
    '',
  ].join('\n');
}

/**
 * Writes the generated file (unless `check`); says whether it was already right.
 * @param {{ root?: string, check?: boolean }} [options]
 * @returns {{ sha256: string, upToDate: boolean, written: boolean }}
 */
export function syncPricingHash({ root = ROOT, check = false } = {}) {
  const sha256 = pricingSha256(root);
  const target = path.join(root, HASH_FILE);
  const wanted = renderHashFile(sha256);
  const upToDate = existsSync(target) && readFileSync(target, 'utf8') === wanted;
  if (upToDate || check) return { sha256, upToDate, written: false };
  writeFileSync(target, wanted);
  return { sha256, upToDate, written: true };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const { sha256, upToDate, written } = syncPricingHash({ check });
  if (check && !upToDate) {
    console.error(
      `${HASH_FILE} is not the hash of ${PRICING_FILE} (${sha256}). Run: npm run pricing:hash`
    );
    process.exit(1);
  }
  console.info(
    written ? `${HASH_FILE} written: ${sha256}` : `${HASH_FILE} is up to date: ${sha256}`
  );
}
